class CodeGenerator:
    """Generates the modular ``ui`` package of a form.

    Files fall in two groups. *Managed* files (``Qt.py``, ``qt_compat.py``,
    the ``theme`` package and the compiled form ``ui_<form>.py``) are
    written on every run. *User-owned* files (the window class, ``main.py``
    and the ``widgets`` package) are created once and then left alone, so
    the form can be edited in Qt Designer and generated again without
    losing hand-written code.

    Example:
        >>> parser = UIParser()
        >>> parser.load("main.ui")
        >>> config = ProjectConfig.load("ui_config.json", LIGHT, DARK)
        >>> CodeGenerator(parser, config).generate("src/ui")
    """

    def __init__(
        self,
        parser: UIParser,
        config: ProjectConfig,
        templates_dir: str | Path | None = None,
    ) -> None:
        self._parser = parser
        self._config = config
        self._templates = Path(templates_dir) if templates_dir else TEMPLATES_DIR

    def generate(self, output: str | Path, force: bool = False) -> GenerationResult:
        """Generates the package.

        Args:
            output: Folder of the package, e.g. ``src/ui``. Its name is
                the package name, so it must be a valid identifier.
            force: Also overwrite the user-owned files.

        Returns:
            GenerationResult: The files written and kept, and warnings.

        Raises:
            GeneratorError: If the form, palettes or output are invalid,
                or the form cannot be compiled.
        """
        output = Path(output)
        top = self._parser.build_tree()
        if top is None:
            raise GeneratorError("The form does not contain any widget.")
        if not output.name.isidentifier():
            raise GeneratorError(
                f"'{output.name}' cannot be a Python package name."
            )
        palettes = self._validated_palettes()

        result = GenerationResult(output=output)
        orphans = self._config.apply_to_parser(self._parser)
        if orphans:
            result.warnings.append(
                f"Roles ignored, no such widget: {', '.join(sorted(orphans))}."
            )

        name = top.name
        module = snake_name(name)
        if module in RESERVED_NAMES:
            module = f"{module}_form"
        base = top.class_name
        if base not in WRAPPER_BASES:
            result.warnings.append(
                f"Unsupported top-level class {base}, the window inherits QWidget."
            )
            base = "QWidget"

        promoted = self._parser.custom_widgets()
        compiled = compile_ui(self._parser.to_string(), module)
        compiled, warnings = patch_uic_imports(compiled, [w.class_name for w in promoted])
        result.warnings.extend(warnings)

        # Managed files
        self._copy(self._templates / "Qt.py", output / "vendor" / "Qt.py", result)
        self._copy(self._templates / "qt_compat.py", output / "qt_compat.py", result)
        self._write(output / "theme" / "__init__.py", THEME_INIT, result)
        self._write(output / "theme" / "colors.py", render_colors(palettes), result)
        self._copy(self._templates / "stylesheet.py", output / "theme" / "stylesheet.py", result)
        self._copy(self._templates / "theme.py", output / "theme" / "theme.py", result)
        self._write(output / f"ui_{module}.py", compiled, result)

        # User-owned files
        self._write(output / "__init__.py", '"""Generated UI package.\n"""\n', result, owned=True, force=force)
        self._write(
            output / "widgets" / "__init__.py",
            '"""Reusable widgets of the application.\n"""\n',
            result,
            owned=True,
            force=force,
        )
        self._write(
            output / f"{module}.py", render_window(name, module, base), result, owned=True, force=force
        )
        self._write(
            output / "main.py", render_main(name, module, output.name), result, owned=True, force=force
        )
        self._write_custom_widgets(output / "widgets" / "custom_widgets.py", promoted, result, force)

        log.info(
            "Generated package %s",
            output,
            written=len(result.written),
            kept=len(result.kept),
        )
        return result

    # region Internal Helpers

    def _validated_palettes(self) -> dict[str, dict[str, str]]:
        """Checks the palettes before they are written to code.

        Returns:
            dict[str, dict[str, str]]: Normalized palettes by theme.

        Raises:
            GeneratorError: If a color is missing or invalid.
        """
        template = self._load_template_palettes()
        palettes: dict[str, dict[str, str]] = {}
        for theme in ("light", "dark"):
            stored = self._config.palettes.get(theme, {})
            missing = [key for key in template[theme] if key not in stored]
            if missing:
                raise GeneratorError(
                    f"The {theme} palette lacks: {', '.join(missing)}."
                )
            try:
                palettes[theme] = {k: normalize_hex(v) for k, v in stored.items()}
            except ConfigError as err:
                raise GeneratorError(f"Invalid {theme} palette: {err}") from err
        return palettes

    def _load_template_palettes(self) -> dict[str, dict[str, str]]:
        """Reads the default palettes of the colors template.

        Returns:
            dict[str, dict[str, str]]: Default colors by theme.

        Raises:
            GeneratorError: If the template cannot be read.
        """
        path = self._templates / "colors.py"
        try:
            tree = ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
            found: dict[str, dict[str, str]] = {}
            for node in tree.body:
                if isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
                    target, value = node.target.id, node.value
                elif (
                    isinstance(node, ast.Assign)
                    and len(node.targets) == 1
                    and isinstance(node.targets[0], ast.Name)
                ):
                    target, value = node.targets[0].id, node.value
                else:
                    continue
                if target in ("LIGHT", "DARK") and value is not None:
                    found[target] = ast.literal_eval(value)
            return {"light": found["LIGHT"], "dark": found["DARK"]}
        except (OSError, SyntaxError, ValueError, KeyError) as err:
            raise GeneratorError(f"Unable to read template '{path}': {err}") from err

    def _write(
        self,
        path: Path,
        text: str,
        result: GenerationResult,
        owned: bool = False,
        force: bool = False,
    ) -> None:
        """Writes a text file, unless it is user-owned and already exists.

        Args:
            path: Destination file.
            text: Content to write.
            result: Result that records the outcome.
            owned: Whether the file belongs to the user once created.
            force: Overwrite even user-owned files.

        Raises:
            GeneratorError: If the file cannot be written.
        """
        if owned and path.exists() and not force:
            result.kept.append(path)
            return
        try:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8", newline="\n")
        except OSError as err:
            raise GeneratorError(f"Unable to write '{path}': {err}") from err
        result.written.append(path)

    def _copy(self, source: Path, destination: Path, result: GenerationResult) -> None:
        """Copies a template file.

        Args:
            source: Template file.
            destination: Destination file.
            result: Result that records the outcome.

        Raises:
            GeneratorError: If the copy fails.
        """
        try:
            destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copyfile(source, destination)
        except OSError as err:
            raise GeneratorError(f"Unable to copy '{source}': {err}") from err
        result.written.append(destination)

    def _write_custom_widgets(
        self,
        path: Path,
        promoted: list[CustomWidgetInfo],
        result: GenerationResult,
        force: bool,
    ) -> None:
        """Creates the promoted widget stubs, or appends the missing ones.

        Args:
            path: ``custom_widgets.py`` file.
            promoted: Widgets promoted in the form.
            result: Result that records the outcome.
            force: Recreate the file from scratch.
        """
        existing = ""
        if path.exists() and not force:
            existing = path.read_text(encoding="utf-8")
        defined = set(re.findall(r"^class (\w+)", existing, flags=re.M))

        stubs: list[str] = []
        for widget in promoted:
            if widget.class_name in defined:
                continue
            base = widget.extends
            if base in NON_WIDGETS_BASES or not base.startswith("Q"):
                result.warnings.append(
                    f"{widget.class_name} extends {base}, which is not in QtWidgets: "
                    "the stub inherits QWidget, adjust it by hand."
                )
                base = "QWidget"
            stubs.append(render_custom_widget(widget, base))

        if not existing:
            self._write(path, CUSTOM_WIDGETS_HEADER + "\n".join(stubs), result)
        elif stubs:
            self._write(path, existing.rstrip("\n") + "\n\n" + "\n".join(stubs), result)
        else:
            result.kept.append(path)

    # endregion

# endregion
