# region Compilation Helpers

def find_uic() -> list[str]:
    """Finds a way to run ``pyside6-uic``.

    Returns:
        list[str]: Command prefix to which the ``.ui`` path is appended.

    Raises:
        GeneratorError: If PySide6 is not installed.
    """
    executable = shutil.which("pyside6-uic")
    if executable:
        return [executable]

    code = (
        "import sys; from PySide6.scripts.pyside_tool import uic; "
        "sys.argv = ['pyside6-uic'] + sys.argv[1:]; uic()"
    )
    probe = subprocess.run(
        [sys.executable, "-c", "import PySide6.scripts.pyside_tool"],
        capture_output=True,
    )
    if probe.returncode == 0:
        return [sys.executable, "-c", code]
    raise GeneratorError(
        "pyside6-uic was not found. Install PySide6 (pip install PySide6)."
    )


def compile_ui(xml: str, form_name: str) -> str:
    """Compiles a form to Python with ``pyside6-uic``.

    Args:
        xml: Content of the ``.ui`` file.
        form_name: File stem used in the generated header comment.

    Returns:
        str: The compiled Python source.

    Raises:
        GeneratorError: If the compiler fails.
    """
    command = find_uic()
    with tempfile.TemporaryDirectory() as folder:
        source = Path(folder) / f"{form_name}.ui"
        source.write_text(xml, encoding="utf-8")
        try:
            run = subprocess.run(
                command + [str(source)],
                capture_output=True,
                text=True,
                encoding="utf-8",
                timeout=60,
            )
        except (OSError, subprocess.TimeoutExpired) as err:
            raise GeneratorError(f"pyside6-uic could not run: {err}") from err

    if run.returncode != 0 or not run.stdout.strip():
        raise GeneratorError(f"pyside6-uic failed: {run.stderr.strip() or 'no output'}")
    return run.stdout


def patch_uic_imports(code: str, promoted: list[str]) -> tuple[str, list[str]]:
    """Rewrites the imports of compiled form code for the generated package.

    Qt imports go through ``Qt.py`` and promoted widgets come from
    ``widgets/custom_widgets.py``.

    Args:
        code: Output of ``pyside6-uic``.
        promoted: Names of the promoted widgets that have a stub.

    Returns:
        tuple[str, list[str]]: The patched code and the warnings found.
    """
    warnings: list[str] = []
    code = re.sub(r"^from PySide6\.(\w+) import", r"from Qt.\1 import", code, flags=re.M)
    code = code.replace("\r\n", "\n")

    for name in promoted:
        code = re.sub(
            rf"^from \S+ import {re.escape(name)}$",
            f"from .widgets.custom_widgets import {name}",
            code,
            flags=re.M,
        )

    first = re.search(r"^from Qt\.", code, flags=re.M)
    marker = "from . import qt_compat  # noqa: F401 (makes Qt.py importable)\n"
    if first:
        code = code[: first.start()] + marker + code[first.start():]

    for match in re.finditer(r"^import (\w+_rc)$", code, flags=re.M):
        warnings.append(
            f"The form uses the resource module '{match.group(1)}': "
            "compile your .qrc file and place it next to the generated form."
        )
    return code, warnings

