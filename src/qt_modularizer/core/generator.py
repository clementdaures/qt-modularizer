# region Exceptions & Data Models

class GeneratorError(Exception):
    """Raised when the code cannot be generated."""


@dataclass
class GenerationResult:
    """Outcome of a generation run.

    Attributes:
        output: Folder the package was generated in.
        written: Files created or overwritten.
        kept: Existing files left untouched because they belong to the user.
        warnings: Points that need the user's attention.
    """

    output: Path
    written: list[Path] = field(default_factory=list)
    kept: list[Path] = field(default_factory=list)
    warnings: list[str] = field(default_factory=list)

# endregion

