def render_custom_widget(widget: CustomWidgetInfo, base: str) -> str:
    """Renders the stub class of a promoted widget.

    Args:
        widget: The promoted widget.
        base: Class of ``QtWidgets`` it inherits from.

    Returns:
        str: Source code of the class, wrapped in its own region.
    """
    return (
        "# ==========\n\n"
        f"# region {widget.class_name}\n\n"
        f"class {widget.class_name}(QtWidgets.{base}):\n"
        f'    """Promoted widget, extends ``{widget.extends}``."""\n\n'
        "# endregion\n"
    )


